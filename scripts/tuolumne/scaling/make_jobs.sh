#!/bin/bash
# Writes the concrete scaling job scripts into this directory, one per point:
#   make_jobs.sh <run_name> <label> <np> <N> <queue> <time_limit> [driver args...]
# e.g.
#   make_jobs.sh scaling_strong_np16 strong 16 500000 pdebug 30m
# BASIS=ct in the environment targets the CartesianTaylorBasis driver, built
# in its own tree (scaling_build_ct) so rebuilding it never touches the
# Laplace binary that Laplace jobs run:
#   BASIS=ct make_jobs.sh scaling_ct_strong_np16 strong 16 500000 pdebug 30m
# Ranks run one per MI300A APU, 4 per node. Raw driver output goes to
# /p/lustre5/stewartj/Canopy/<run_name>/driver.<jobid>.log; the flux log
# ({{name}}.{{jobid}}.log in the submit directory) keeps provenance and the
# marker lines only.
set -e
here=$(cd "$(dirname "$0")" && pwd)
run=$1 label=$2 np=$3 n=$4 queue=$5 tlim=$6
shift 6
extra="$*"
case "${BASIS:-laplace}" in
    laplace) build=scaling_build exe=scaling_breakdown ;;
    ct) build=scaling_build_ct exe=scaling_breakdown_ct ;;
    *) echo "BASIS must be laplace or ct" >&2; exit 1 ;;
esac
nodes=$(( (np + 3) / 4 ))
out=${here}/${run}.flux

cat > "${out}" <<EOF
#!/bin/bash
# flux: --job-name=canopy-${run}
# flux: --nodes=${nodes}
# flux: --exclusive
# flux: --time-limit=${tlim}
# flux: --output={{name}}.{{jobid}}.log
# flux: -q ${queue}
#
# Generated by scripts/tuolumne/scaling/make_jobs.sh — see figures/CLAUDE.md.
# ${label} scaling point: np=${np} (${nodes} node(s), 1 rank per APU), N=${n}.
#
# Submit from the canopy checkout:
#   flux batch scripts/tuolumne/scaling/${run}.flux

source /usr/workspace/stewartj/spack/share/spack/setup-env.sh
spack env activate \${HOME}/spack_envs/tuolumne_trilinos

CANOPY_SRC=/g/g20/stewartj/research-bridges/canopy-dev/Canopy
CANOPY_BUILD=/p/lustre5/stewartj/Canopy/${build}/build
EXE=\${CANOPY_BUILD}/examples/05_scaling_breakdown/${exe}
OUTDIR=/p/lustre5/stewartj/Canopy/${run}
mkdir -p \${OUTDIR}

export MPICH_GPU_SUPPORT_ENABLED=1
export GTL_HSA_VSMSG_CUTOFF_SIZE=4096
export FI_CXI_ATS=0
export HSA_XNACK=1
export MPICH_SMP_SINGLE_COPY_MODE=NONE
export OMP_NUM_THREADS=8
export OMP_PROC_BIND=close
export OMP_PLACES=cores
export OMP_WAIT_POLICY=PASSIVE
# Cray static-TLS workaround (systems/tuolumne/claude.md).
export GLIBC_TUNABLES=glibc.rtld.optional_static_tls=2000000

JOBID=\$(flux job id --to=f58 "\$(flux getattr jobid 2>/dev/null)" 2>/dev/null || echo unknown)
LOG=\${OUTDIR}/driver.\${JOBID}.log

{
echo "=== provenance ==="
echo "run: ${run} label=${label} np=${np} nodes=${nodes} N=${n} extra='${extra}'"
echo "jobid: \${JOBID}"
echo "host: \$(hostname)"
echo "git HEAD: \$(git -C \${CANOPY_SRC} rev-parse HEAD)"
git -C \${CANOPY_SRC} status --porcelain -- src examples
echo "build: \${CANOPY_BUILD}"
grep -E '^Canopy_ENABLE_PROFILING:|^Canopy_PROFILING_LEVEL:' \${CANOPY_BUILD}/CMakeCache.txt
echo "binary: \$(stat -c '%y' \${EXE}) md5 \$(md5sum \${EXE} | cut -d' ' -f1)"
echo "driver log: \${LOG}"
echo "=================="
} | tee \${OUTDIR}/provenance.\${JOBID}.txt

# Core files from the multi-node exit segfault (README Known Issues) land here.
cd \${OUTDIR}
set -o pipefail
flux run --ntasks=${np} --nodes=${nodes} --exclusive \\
    --gpus-per-task=1 --cores-per-task=8 \\
    --setopt=mpibind=verbose:1 \\
    \${EXE} -N ${n} -l ${label} ${extra} 2>&1 | tee \${LOG} | \\
    grep --line-buffered -E '^### CANOPY_SCALING (config|end|done)|WARNING|[Ee]rror|abort|Abort'
# grep exits 1 when it matched nothing; the driver's status is what counts.
rc=\${PIPESTATUS[0]}
echo "### driver rc=\${rc} log=\${LOG}"
exit \${rc}
EOF
chmod +x "${out}"
echo "${out}"
